import json
import tempfile
from pathlib import Path

import streamlit as st

from evaluate_safety_system import (
    evaluate,
    load_gold_annotations,
    load_system_predictions,
)
from evaluation_metrics import cohen_kappa


ROOT = Path(__file__).resolve().parent
DEFAULT_REPORTS_DIR = ROOT / "reports" / "scenario_evaluation_runs"


def _format_metric(value):
    return "Undefined" if value is None else f"{value:.3f}"


st.title("Research methods and evaluation")
st.write(
    "This workspace follows the capstone proposal's dataset separation, "
    "human annotation, quantitative evaluation, and reproducibility "
    "requirements."
)

st.header("Evaluation design")
st.markdown(
    """
1. Select scenarios that are independent of detector training, validation,
   and locked detector test images.
2. Label every image/category pair as positive, negative, or uncertain using
   the published annotation guide.
3. Preserve independent rater labels; adjudicate disagreements without
   replacing the original ratings.
4. Freeze model checkpoints, rules, and thresholds before evaluating the
   independent test set.
5. Report category-level performance, uncertainty exclusions, reviewer
   agreement, and qualitative explanation/recommendation findings separately.
"""
)

with st.expander("Annotation unit and supported categories", expanded=True):
    st.write(
        "One row represents an image and one supported screening category. "
        "The current evaluator accepts `potential_missing_ppe` and "
        "`potential_worker_machinery_interaction`. A missing model detection "
        "is not a gold negative by itself."
    )
    st.code(
        "image_id,finding_category,ground_truth,rater_1,rater_2\n"
        "scenario_001.jpg,potential_missing_ppe,uncertain,uncertain,0",
        language="csv",
    )
    template = (
        "image_id,finding_category,ground_truth,rater_1,rater_2\n"
        "scenario_001.jpg,potential_missing_ppe,uncertain,uncertain,0\n"
        "scenario_001.jpg,potential_worker_machinery_interaction,0,0,0\n"
    )
    st.download_button(
        "Download annotation CSV template",
        data=template,
        file_name="scenario_annotation_template.csv",
        mime="text/csv",
    )

st.header("Evaluate an independently labeled scenario set")
st.warning(
    "Do not point this tool at the existing detector test sets, use their "
    "labels for tuning, or treat the 40-image duplicate review as scenario "
    "ground truth.",
    icon=":material/lock:",
)

annotations_file = st.file_uploader(
    "Upload the completed scenario annotation CSV",
    type=["csv"],
)
reports_dir_text = st.text_input(
    "Directory containing one fresh detections.json report per scenario",
    value=str(DEFAULT_REPORTS_DIR),
    help=(
        "Use reports generated by the current graph/rule implementation. "
        "Legacy reports without safety_assessment are not compatible."
    ),
)

if st.button(
    "Evaluate labeled scenarios",
    type="primary",
    disabled=annotations_file is None,
):
    reports_dir = Path(reports_dir_text).expanduser()
    if not reports_dir.is_absolute():
        reports_dir = (ROOT / reports_dir).resolve()
    if not reports_dir.is_dir():
        st.error(f"Reports directory does not exist: {reports_dir}")
        st.stop()

    try:
        with tempfile.TemporaryDirectory(
            prefix="construction-safety-annotations-"
        ) as temp_dir:
            annotation_path = Path(temp_dir) / "annotations.csv"
            annotation_path.write_bytes(annotations_file.getvalue())
            annotations, raters = load_gold_annotations(annotation_path)

        predictions = load_system_predictions(
            reports_dir,
            {image_id for image_id, _ in annotations},
        )
        report = evaluate(annotations, predictions)

        if "rater_1" in raters and "rater_2" in raters:
            report["inter_rater_agreement"] = {
                "measure": "Cohen's kappa",
                "paired_labels": len(raters["rater_1"]),
                "excluded_uncertain_pairs": raters[
                    "excluded_uncertain_pairs"
                ],
                "value": (
                    cohen_kappa(raters["rater_1"], raters["rater_2"])
                    if raters["rater_1"] else None
                ),
                "scope": "Paired binary image-level annotations.",
            }

    except (OSError, ValueError, json.JSONDecodeError) as error:
        st.error(f"Evaluation could not be completed: {error}")
        st.stop()

    st.subheader("Evaluation results")
    metrics = report["overall"]
    with st.container(horizontal=True):
        st.metric("Evaluated pairs", metrics["support"])
        st.metric("Precision", _format_metric(metrics["precision"]))
        st.metric("Recall", _format_metric(metrics["recall"]))
        st.metric("F1", _format_metric(metrics["f1"]))
    st.write("**Per-category metrics**")
    st.dataframe(
        [
            {"Category": category, **values}
            for category, values in report["categories"].items()
        ],
        hide_index=True,
        width="stretch",
        alt="Image-level safety finding metrics by supported category",
    )
    st.write("**Annotation coverage and exclusions**")
    st.json(report["annotation_summary"])
    if "inter_rater_agreement" in report:
        st.write("**Inter-rater agreement**")
        st.json(report["inter_rater_agreement"])
    st.download_button(
        "Download evaluation report",
        data=json.dumps(report, indent=2),
        file_name="integrated_safety_evaluation.json",
        mime="application/json",
    )
